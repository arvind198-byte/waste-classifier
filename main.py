import io
import os
from contextlib import asynccontextmanager

# Set the backend before importing Keras.
os.environ.setdefault("KERAS_BACKEND", "tensorflow")

import keras
import numpy as np
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from keras.applications.resnet50 import preprocess_input
from PIL import Image, UnidentifiedImageError
from huggingface_hub import hf_hub_download
MODEL_ID = "hf://Stefaron/trash-classifier"
IMAGE_SIZE = (384, 384)
MAX_IMAGE_BYTES = 10 * 1024 * 1024

# TrashNet classes are conventionally ordered alphabetically, as generated by
# Keras directory-based dataset loaders. Verify predictions during testing.
CLASSES = ["cardboard", "glass", "metal", "paper", "plastic", "trash"]

DISPOSAL_GUIDANCE = {
    "cardboard": "Keep cardboard clean and dry, flatten it, and place it in your local paper/cardboard recycling stream if accepted.",
    "glass": "Handle broken glass carefully. Separate glass according to local collection rules; not every glass item is accepted in bottle banks.",
    "metal": "Empty and rinse metal packaging where practical, then use your local metal-recycling collection if available.",
    "paper": "Keep paper clean and dry and send it for paper recycling where accepted. Greasy or food-soiled paper may not be recyclable.",
    "plastic": "Empty and rinse the item if practical. Check local rules because recycling acceptance varies by plastic type and location.",
    "trash": "The model classified this as general trash. Check whether it is actually e-waste, a battery, chemical, or another special-waste item before disposal.",
}

model = None

@asynccontextmanager
async def lifespan(app: FastAPI):
    global model
    print(f"Loading waste classifier: {MODEL_ID}")
    model_path = hf_hub_download(
    repo_id="Stefaron/trash-classifier",
    filename="best_model.keras",
    )

    model = keras.saving.load_model(model_path) 
    print("Waste classifier loaded.")
    yield
    model = None

app = FastAPI(
    title="AI Waste Identification and Segregation Assistant",
    description="Classifies waste images into six TrashNet categories and provides general disposal guidance.",
    version="1.0.0",
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173", "http://127.0.0.1:5173"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

@app.get("/health")
def health():
    return {"status": "ok", "model_loaded": model is not None}

@app.post("/predict")
async def predict(file: UploadFile = File(...)):
    if model is None:
        raise HTTPException(status_code=503, detail="Model is not loaded yet. Wait a moment and retry.")

    if file.content_type and not file.content_type.startswith("image/"):
        raise HTTPException(status_code=415, detail="Upload an image file (JPG, PNG, or WEBP).")

    raw = await file.read()
    if not raw:
        raise HTTPException(status_code=400, detail="The uploaded file is empty.")
    if len(raw) > MAX_IMAGE_BYTES:
        raise HTTPException(status_code=413, detail="Image is too large. Use an image under 10 MB.")

    try:
        with Image.open(io.BytesIO(raw)) as opened:
            image = opened.convert("RGB").resize(IMAGE_SIZE)
    except (UnidentifiedImageError, OSError):
        raise HTTPException(status_code=400, detail="Could not read this image. Try a JPG, PNG, or WEBP file.")

    pixels = np.asarray(image, dtype=np.float32)
    pixels = preprocess_input(pixels)
    batch = np.expand_dims(pixels, axis=0)

    try:
        raw_scores = np.asarray(model.predict(batch, verbose=0)[0], dtype=np.float64).reshape(-1)
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Model inference failed: {type(exc).__name__}")

    if len(raw_scores) != len(CLASSES):
        raise HTTPException(status_code=500, detail=f"Model returned {len(raw_scores)} scores; expected {len(CLASSES)}.")

    # Normalize only if the model output is not already a probability vector.
    if np.any(raw_scores < 0) or not np.isclose(float(raw_scores.sum()), 1.0, atol=0.05):
        shifted = raw_scores - np.max(raw_scores)
        exp_scores = np.exp(shifted)
        scores = exp_scores / exp_scores.sum()
    else:
        scores = raw_scores / raw_scores.sum()

    best_idx = int(np.argmax(scores))
    category = CLASSES[best_idx]
    confidence = float(scores[best_idx])
    return {
        "category": category,
        "confidence_percent": round(confidence * 100, 2),
        "guidance": DISPOSAL_GUIDANCE[category],
        "low_confidence": confidence < 0.45,
        "scores": {name: round(float(score) * 100, 2) for name, score in zip(CLASSES, scores)},
        "note": "Prediction scores are model estimates, not calibrated guarantees. Follow local waste-management rules.",
    }
